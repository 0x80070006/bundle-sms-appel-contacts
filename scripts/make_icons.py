"""Generates the bundle's launcher icons and icon-colour aliases for the three apps.

Each app gets one white glyph (person, handset, speech bubble) on a coloured adaptive-icon
background: its own colour by default, or one of the colours the user can pick in Appearance
(black for a dark home screen, and the others). Android can't recolour an installed icon, so each
colour is an <activity-alias> with its own icon; the app enables the chosen one.

Run from the monorepo root: python scripts/make_icons.py
It rewrites the generated files and the block between the BUNDLE-ICONS markers in each manifest.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# key, ARGB, used by Appearance's picker (same list in core/appearance/AppIcons.kt).
COLORS = [
    ("Black", "#FF000000"),
    ("Blue", "#FF1A73E8"),
    ("Green", "#FF188038"),
    ("Orange", "#FFD2550A"),
    ("Red", "#FFC5221F"),
    ("Pink", "#FFC2185B"),
    ("Purple", "#FF7B1FA2"),
    ("Indigo", "#FF3949AB"),
    ("Teal", "#FF00796B"),
    ("Graphite", "#FF3C4043"),
]

PERSON = "M12,12c2.21,0 4,-1.79 4,-4s-1.79,-4 -4,-4 -4,1.79 -4,4 1.79,4 4,4zM12,14c-2.67,0 -8,1.34 -8,4v2h16v-2c0,-2.66 -5.33,-4 -8,-4z"
HANDSET = (
    "M20.01,15.38c-1.23,0 -2.42,-0.2 -3.53,-0.56 -0.35,-0.12 -0.74,-0.03 -1.01,0.24l-1.57,1.97"
    "c-2.83,-1.35 -5.48,-3.9 -6.89,-6.83l1.95,-1.66c0.27,-0.28 0.35,-0.67 0.24,-1.02"
    " -0.37,-1.11 -0.56,-2.3 -0.56,-3.53 0,-0.54 -0.45,-0.99 -0.99,-0.99H4.19C3.65,3 3,3.24 3,3.99"
    " 3,13.28 10.73,21 20.01,21c0.71,0 0.99,-0.63 0.99,-1.18v-3.45c0,-0.54 -0.45,-0.99 -0.99,-0.99z"
)
BUBBLE = (
    "M20,2H4c-1.1,0 -2,0.9 -2,2v18l4,-4h14c1.1,0 2,-0.9 2,-2V4c0,-1.1 -0.9,-2 -2,-2z"
    "M6.75,10a1.25,1.25 0,1 0,2.5 0a1.25,1.25 0,1 0,-2.5 0z"
    "M10.75,10a1.25,1.25 0,1 0,2.5 0a1.25,1.25 0,1 0,-2.5 0z"
    "M14.75,10a1.25,1.25 0,1 0,2.5 0a1.25,1.25 0,1 0,-2.5 0z"
)

APPS = [
    # name, res dir, manifest, glyph, default colour, launcher activity, mipmap dir of ic_launcher
    dict(name="contacts", res="apps/contacts/app/src/main/res", manifest="apps/contacts/app/src/main/AndroidManifest.xml",
         glyph=PERSON, color="Orange", target="app.people.contacts.MainActivity", default_alias="bundle.launcher.Default",
         launcher_xml=["mipmap-anydpi/ic_launcher.xml"]),
    dict(name="phone", res="apps/phone/app/src/main/res", manifest="apps/phone/app/src/main/AndroidManifest.xml",
         glyph=HANDSET, color="Green", target="app.dialtone.phone.MainActivity", default_alias="bundle.launcher.Default",
         launcher_xml=["mipmap-anydpi-v26/ic_launcher.xml", "mipmap-anydpi-v26/ic_launcher_round.xml"]),
    dict(name="messages", res="apps/messages/res", manifest="apps/messages/AndroidManifest.xml",
         glyph=BUBBLE, color="Blue", target="com.android.messaging.ui.MainActivity",
         default_alias="com.android.messaging.ui.conversationlist.ConversationListActivity",
         launcher_xml=["mipmap-anydpi-v26/ic_launcher.xml"]),
]

HEADER = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by scripts/make_icons.py: edit the script, not this file. -->\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def adaptive(color_ref):
    return HEADER + (
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f'    <background android:drawable="{color_ref}" />\n'
        '    <foreground android:drawable="@drawable/bundle_icon_glyph" />\n'
        '    <monochrome android:drawable="@drawable/bundle_icon_glyph" />\n'
        '</adaptive-icon>\n'
    )


for app in APPS:
    res = os.path.join(ROOT, app["res"])
    default_hex = dict(COLORS)[app["color"]]
    # The glyph: 24-unit Material path, scaled to 54 units in the middle of the 108-unit icon
    # (inside the 66-unit safe zone every launcher mask keeps).
    write(os.path.join(res, "drawable", "bundle_icon_glyph.xml"), HEADER + (
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n'
        '    <group android:translateX="27" android:translateY="27" android:scaleX="2.25" android:scaleY="2.25">\n'
        f'        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{app["glyph"]}" />\n'
        '    </group>\n'
        '</vector>\n'
    ))
    colors = "".join(f'    <color name="bundle_icon_{k.lower()}">{v}</color>\n' for k, v in COLORS)
    write(os.path.join(res, "values", "bundle_icon_colors.xml"), HEADER + (
        "<resources>\n"
        f'    <color name="bundle_icon_default">{default_hex}</color>\n{colors}</resources>\n'
    ))
    for rel in app["launcher_xml"]:
        write(os.path.join(res, rel), adaptive("@color/bundle_icon_default"))
    for key, _ in COLORS:
        if key == app["color"]:
            continue
        write(os.path.join(res, "mipmap-anydpi-v26", f"bundle_ic_{key.lower()}.xml"), adaptive(f"@color/bundle_icon_{key.lower()}"))

    # Manifest: one disabled alias per colour, between the markers (added the first time).
    path = os.path.join(ROOT, app["manifest"])
    text = open(path, encoding="utf-8").read()
    aliases = []
    if app["default_alias"].startswith("bundle."):
        aliases.append(
            f'        <activity-alias\n            android:name="{app["default_alias"]}"\n'
            f'            android:targetActivity="{app["target"]}"\n'
            '            android:exported="true">\n'
            '            <intent-filter>\n'
            '                <action android:name="android.intent.action.MAIN" />\n'
            '                <category android:name="android.intent.category.LAUNCHER" />\n'
            '            </intent-filter>\n'
            '        </activity-alias>\n'
        )
    for key, _ in COLORS:
        if key == app["color"]:
            continue
        aliases.append(
            f'        <activity-alias\n            android:name="bundle.launcher.{key}"\n'
            f'            android:targetActivity="{app["target"]}"\n'
            f'            android:icon="@mipmap/bundle_ic_{key.lower()}"\n'
            f'            android:roundIcon="@mipmap/bundle_ic_{key.lower()}"\n'
            '            android:enabled="false"\n'
            '            android:exported="true">\n'
            '            <intent-filter>\n'
            '                <action android:name="android.intent.action.MAIN" />\n'
            '                <category android:name="android.intent.category.LAUNCHER" />\n'
            '            </intent-filter>\n'
            '        </activity-alias>\n'
        )
    block = ("        <!-- BUNDLE-ICONS: launcher icon colours, chosen in Appearance (scripts/make_icons.py). -->\n"
             + "".join(aliases) + "        <!-- /BUNDLE-ICONS -->\n")
    if "BUNDLE-ICONS" in text:
        text = re.sub(r"        <!-- BUNDLE-ICONS.*?<!-- /BUNDLE-ICONS -->\n", lambda m: block, text, flags=re.S)
    else:
        text = text.replace("    </application>", block + "    </application>", 1)
    write(path, text)
    print(app["name"], "ok")
